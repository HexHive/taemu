#!/usr/bin/env python3
"""Differential-testing oracle: emulator vs. real device.

The emulator's Python GP lib is an approximation -- heap layout, uninitialized
memory, allocator quirks and crypto edge cases differ from the real TEE. So a
finding that reproduces in emulation may not on hardware, and vice versa. This
module is the *oracle*: it defines a portable test "vector" (one InvokeCommand:
command id + param types + the four params) and a "record" (what came back:
return code/origin + the out-direction params), and `compare()`s an emulator
record against a device record, reporting every divergence.

You don't need a bespoke emulator runner: this project already compiles a single
POC source against BOTH the emulator (`-DEMULATE`, over the :1337 socket) and the
phone (Android NDK + real libTEEC). So one vector-driven POC produces both
records:

    vector.py genheader vec.json > difftest/vector.h   # bake the vector in
    (cd difftest && make emulator && ./poc > emu.json)  # vs emulator
    (cd difftest && make phone && adb ... ./poc > dev.json)  # vs device
    vector.py compare emu.json dev.json                 # -> divergences

See difftest_poc.c and README.md. This file has no third-party deps.
"""
import json
import sys

# GP TEEC param-type tags -> the slot's data direction (does the TA write it?).
PARAM_TYPES = {
    "NONE": (False, False),
    "VALUE_INPUT": (True, False),
    "VALUE_OUTPUT": (False, True),
    "VALUE_INOUT": (True, True),
    "MEMREF_TEMP_INPUT": (True, False),
    "MEMREF_TEMP_OUTPUT": (False, True),
    "MEMREF_TEMP_INOUT": (True, True),
}


def is_output(ptype):
    """Does the TA write this slot (so it belongs in the output record)?"""
    return PARAM_TYPES.get(ptype, (False, False))[1]


def load(path):
    with open(path) as f:
        return json.load(f)


def save(obj, path):
    with open(path, "w") as f:
        json.dump(obj, f, indent=2)


def compare(emu, dev):
    """Diff an emulator record against a device record. Returns a list of
    human-readable divergence strings (empty == records agree)."""
    div = []

    def norm_rc(r):
        v = r.get("return_code")
        if isinstance(v, str):
            return int(v, 0)
        return v

    if norm_rc(emu) != norm_rc(dev):
        div.append(
            f"return_code: emu={emu.get('return_code')} dev={dev.get('return_code')}"
        )
    if emu.get("return_origin") != dev.get("return_origin"):
        div.append(
            f"return_origin: emu={emu.get('return_origin')} dev={dev.get('return_origin')}"
        )

    pe, pd = emu.get("params_out", []), dev.get("params_out", [])
    if len(pe) != len(pd):
        div.append(f"param count: emu={len(pe)} dev={len(pd)}")
        return div

    for i, (a, b) in enumerate(zip(pe, pd)):
        if a.get("type") != b.get("type"):
            div.append(f"param[{i}] type: emu={a.get('type')} dev={b.get('type')}")
            continue
        if a.get("type") == "value":
            if a.get("a") != b.get("a") or a.get("b") != b.get("b"):
                div.append(
                    f"param[{i}] value: emu=({a.get('a')},{a.get('b')}) "
                    f"dev=({b.get('a')},{b.get('b')})"
                )
        elif a.get("type") == "memref":
            if a.get("size") != b.get("size"):
                div.append(
                    f"param[{i}] memref size: emu={a.get('size')} dev={b.get('size')}"
                )
            ea = bytes.fromhex(a.get("data_hex", ""))
            eb = bytes.fromhex(b.get("data_hex", ""))
            if ea != eb:
                offs = [j for j in range(min(len(ea), len(eb))) if ea[j] != eb[j]]
                head = ", ".join(
                    f"@{j}:{ea[j]:#04x}!={eb[j]:#04x}" for j in offs[:8]
                )
                more = "" if len(offs) <= 8 else f" (+{len(offs) - 8} more)"
                div.append(f"param[{i}] memref bytes differ: {head}{more}")
    return div


def _c_array(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data) or "0"
    return f"static const unsigned char {name}[] = {{ {body} }};\n"


def genheader(vector):
    """Emit a C header baking the vector in, for difftest_poc.c (no C JSON
    parser needed). Encodes each param as a small descriptor the POC iterates."""
    out = ["/* generated by vector.py genheader -- do not edit */\n",
           "#ifndef DIFFTEST_VECTOR_H\n#define DIFFTEST_VECTOR_H\n"]
    out.append(f'#define DT_UUID "{vector["uuid"]}"\n')
    ubytes = bytes.fromhex(vector["uuid"].replace("-", ""))
    if len(ubytes) != 16:
        raise ValueError(f"uuid must be 16 bytes, got {len(ubytes)}")
    out.append(_c_array("DT_UUID_BYTES", ubytes))  # big-endian RFC4122 order
    out.append(f'#define DT_COMMAND_ID {int(vector["command_id"])}\n')
    pts = vector["param_types"]
    macro = "TEEC_PARAM_TYPES(" + ", ".join(f"TEEC_{p}" for p in pts) + ")"
    out.append(f"#define DT_PARAM_TYPES {macro}\n")
    out.append(f"#define DT_NPARAMS {len(pts)}\n")
    for i, p in enumerate(vector["params"]):
        if p["type"] == "memref":
            data = bytes.fromhex(p.get("data_hex", ""))
            out.append(_c_array(f"DT_P{i}_DATA", data))
            out.append(f"#define DT_P{i}_SIZE {int(p.get('size', len(data)))}\n")
        elif p["type"] == "value":
            out.append(f"#define DT_P{i}_A {int(p.get('a', 0))}\n")
            out.append(f"#define DT_P{i}_B {int(p.get('b', 0))}\n")
    out.append("#endif\n")
    return "".join(out)


def _main(argv):
    if len(argv) >= 4 and argv[1] == "compare":
        div = compare(load(argv[2]), load(argv[3]))
        if not div:
            print("MATCH: emulator and device records agree")
            return 0
        print(f"DIVERGENCE ({len(div)}):")
        for d in div:
            print(f"  - {d}")
        return 1
    if len(argv) >= 3 and argv[1] == "genheader":
        sys.stdout.write(genheader(load(argv[2])))
        return 0
    print("usage:\n  vector.py compare <emu.json> <dev.json>\n"
          "  vector.py genheader <vector.json>  > vector.h", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(_main(sys.argv))
