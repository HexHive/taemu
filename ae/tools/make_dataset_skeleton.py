#!/usr/bin/env python3
"""Emit a candidate ae/data/dataset.json for the GlobalPlatform TA dataset.

Table I's '# TAs' column is the number of GlobalPlatform-compliant TAs per TEE.
That subset was determined by manual analysis and cannot be derived from the
shipped corpus, which contains every TA extracted from the firmware images. This
script lists the plausible candidates so the list only has to be *pruned*:

  * TAs that carry emulator metadata (<tee>/tas/<ta>.json) and expose
    TA_InvokeCommandEntryPoint are listed first - those are GlobalPlatform TAs
    as far as the artifact can tell,
  * the remaining TA files are listed in "candidates_without_metadata" so
    nothing is silently dropped (all Kinibi TAs end up here: they are emulated
    with the Beanpod runtime and have no metadata of their own),
  * TAs that already have a harness are marked, since those are by definition
    part of the dataset (they are the '# TAs w/o Local Copy' column).

Usage:
    python3 ae/tools/make_dataset_skeleton.py > ae/data/dataset.json
    $EDITOR ae/data/dataset.json      # delete what is not in the dataset
"""

import glob
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TEES = ["teegris", "qsee", "kinibi", "mitee", "beanpod"]
EXPECTED = {"teegris": 33, "qsee": 4, "kinibi": 6, "mitee": 12, "beanpod": 11}
KINIBI_HARNESSES = {"0801_fuzz", "abcd_fuzz", "df1e_fuzz"}


def harnessed_tas(tee):
    """TA file names that have a harness (Table I, '# TAs w/o Local Copy')."""
    hroot = os.path.join(REPO, "beanpod" if tee == "kinibi" else tee, "harness")
    out = set()
    if not os.path.isdir(hroot):
        return out
    for name in sorted(os.listdir(hroot)):
        if name.startswith("ae_"):
            continue
        # The Kinibi TAs are emulated with the Beanpod runtime, so their
        # harnesses live under beanpod/harness. A TA shipped by both TEEs counts
        # for both (Table II lists ifaa-key as "Kinibi,Beanpod"), which is why
        # beanpod keeps all of its harnesses.
        if tee == "kinibi" and name not in KINIBI_HARNESSES:
            continue
        for ta in glob.glob(os.path.join(hroot, name, "*.ta")):
            out.add(os.path.basename(os.path.realpath(ta)))
    return out


def is_gp(ta_path):
    meta = ta_path[: -len(os.path.splitext(ta_path)[1])] + ".json"
    if not os.path.exists(meta):
        return False
    try:
        d = json.load(open(meta))
    except Exception:
        return False
    return d.get("TA_InvokeCommandEntryPoint_start", -1) not in (-1, None)


def main():
    out = {"_comment": [
        "Candidate GlobalPlatform TA dataset, generated by",
        "ae/tools/make_dataset_skeleton.py. Prune 'gp_tas' to the TAs of Table I;",
        "'candidates_without_metadata' lists TA files the artifact cannot classify",
        "(all Kinibi TAs are here - they run on the Beanpod runtime). Move whatever",
        "belongs to the dataset into 'gp_tas'.",
        "'harnessed' is informational: those TAs operate on shared memory and are",
        "therefore part of the dataset by construction.",
    ]}
    for tee in TEES:
        tas = sorted(glob.glob(os.path.join(REPO, tee, "tas", "*.ta")) +
                     glob.glob(os.path.join(REPO, tee, "tas", "*.tlbin")) +
                     glob.glob(os.path.join(REPO, tee, "tas", "*.tabin")))
        gp, unknown = [], []
        for t in tas:
            (gp if is_gp(t) else unknown).append(os.path.basename(t))
        h = sorted(harnessed_tas(tee))
        out[tee] = {
            "expected_gp_tas": EXPECTED[tee],
            "gp_tas": gp,
            "candidates_without_metadata": unknown,
            "harnessed": h,
        }
        print(f"[{tee}] {len(gp)} with metadata, {len(unknown)} unclassified, "
              f"{len(h)} harnessed (paper: {EXPECTED[tee]} GP TAs)", file=sys.stderr)
    json.dump(out, sys.stdout, indent=2)
    print(file=sys.stdout)


if __name__ == "__main__":
    main()
